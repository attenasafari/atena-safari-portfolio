for (const quiz of quizzes) {
  if (quiz.questions.length !== 5) {
    throw new Error(`${quiz.id} needs 5 questions`);
  }
  for (const question of quiz.questions) {
    if (question.options.length < 2) throw new Error(`${quiz.id} ${question.id} needs options`);
    if (quiz.mode === "scored" && !question.options.some((option) => option.id === question.correctId)) {
      throw new Error(`${quiz.id} ${question.id} has no correct option`);
    }
  }
}

export function getQuiz(id: string) {
  return quizzes.find((quiz) => quiz.id === id);
}

export function quizzesIn(categoryId: CategoryId) {
  return quizzes.filter((quiz) => quiz.categoryId === categoryId);
}
