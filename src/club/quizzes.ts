function opts(pairs: [string, string][]): Option[] {
  return pairs.map(([id, label]) => ({ id, label }));
}

function q(
  id: string,
  format: QuestionFormat,
  prompt: string,
  options: Option[],
  correctId: string,
  explanation: string,
  image?: "crew" | CategoryId,
): Question {
  return { id, format, prompt, options, correctId, explanation, image };
}

function persona(
  id: string,
  prompt: string,
  choices: { id: string; label: string; trait: Trait; note: string }[],
): Question {
  return {
    id,
    format: "personality",
    prompt,
    options: choices,
    explanation: "Nothing here is wrong. Your picks lean the club toward one friend.",
  };
}

